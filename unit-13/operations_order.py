# Part 1: Demonstrating BODMAS

result_without_parentheses = 10 + 5 * 2
result_with_parentheses = (10 + 5) * 2

print("Result without parentheses:", result_without_parentheses)
print("Result with parentheses:", result_with_parentheses)

# Part 2: Score Tracker

score = 50

print("\nStarting Score:", score)

# Add bonus points
score += 10
print("After adding 10 points:", score)

# Deduct penalty points
score -= 5
print("After deducting 5 points:", score)

# Multiply the score
score *= 2
print("After multiplying by 2:", score)

