
# Practising Arithmetic Operators

# Realistic data: A shop selling products

total_sales = 50000
expenses = 15000
product_price = 2500
quantity = 4
items = 17
customers = 5

# Addition (+)
print("Total Sales and Expenses:", total_sales + expenses)

# Subtraction (-)
print("Profit After Expenses:", total_sales - expenses)

# Multiplication (*)
print("Cost of Products:", product_price * quantity)

# Division (/)
print("Average Sales per Customer:", total_sales / customers)

# Floor Division (//)
print("Whole Items per Customer:", items // customers)

# Modulus (%)
print("Remaining Items:", items % customers)

# Exponentiation (**)
print("Squared Product Price:", product_price ** 2)

